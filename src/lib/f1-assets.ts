export function getCircuitImageUrl(circuitId?: string): string {
  if (!circuitId) return "https://oversteer48.com/wp-content/uploads/2024/02/Spa-Francorchamps.jpg";
  const key = circuitId
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9_]/g, "_");
  if (CIRCUIT_PHOTOS[key]) return CIRCUIT_PHOTOS[key];

  const matchKey = Object.keys(CIRCUIT_PHOTOS).find(
    (k) =>
      k === key ||
      k.endsWith(key) ||
      key.endsWith(k) ||
      (key.length >= 4 && k.includes(key)) ||
      (k.length >= 4 && key.includes(k)),
  );
  if (matchKey) return CIRCUIT_PHOTOS[matchKey];

  return "https://oversteer48.com/wp-content/uploads/2024/02/Spa-Francorchamps.jpg";
}

